"""In-memory conversation history manager.

Stores per-user structured conversation turns compatible with the official google-genai SDK.
Enforces a sliding window limit to keep conversations within context limits.
"""

from collections import defaultdict
from google.genai import types
from loguru import logger

from bot.config import config


class MemoryService:
    """Manages multi-turn conversation history for Telegram users."""

    def __init__(self, max_messages: int | None = None) -> None:
        """Initialize in-memory storage.

        Args:
            max_messages: Maximum conversation turns to store per user.
                          Defaults to config.max_history_messages.
        """
        self._max_messages: int = (
            max_messages if max_messages is not None else config.max_history_messages
        )
        self._storage: dict[int, list[types.Content]] = defaultdict(list)

    def add_user_message(self, user_id: int, text: str) -> None:
        """Append a user message turn to the user's history.

        Args:
            user_id: Telegram user identifier.
            text: Text content sent by the user.
        """
        turn = types.Content(
            role="user",
            parts=[types.Part.from_text(text=text)],
        )
        self._add_turn(user_id, turn)

    def add_model_message(self, user_id: int, text: str) -> None:
        """Append a model response turn to the user's history.

        Args:
            user_id: Telegram user identifier.
            text: Text content generated by Gemini.
        """
        turn = types.Content(
            role="model",
            parts=[types.Part.from_text(text=text)],
        )
        self._add_turn(user_id, turn)

    def add_turn(self, user_id: int, content: types.Content) -> None:
        """Append an arbitrary structured Content turn (e.g. multimodal).

        Args:
            user_id: Telegram user identifier.
            content: google.genai types.Content object.
        """
        self._add_turn(user_id, content)

    def _add_turn(self, user_id: int, turn: types.Content) -> None:
        """Internal helper to append a turn and enforce sliding window constraints."""
        history = self._storage[user_id]
        history.append(turn)

        # Enforce max history window
        if len(history) > self._max_messages:
            history = history[-self._max_messages :]

            # Google Gemini conversations must begin with a 'user' turn
            while history and history[0].role != "user":
                history.pop(0)

            self._storage[user_id] = history

        logger.debug(
            f"Foydalanuvchi [{user_id}] xotirasiga yangi turn qo'shildi (role={turn.role}, jami: {len(self._storage[user_id])})"
        )

    def get_history(self, user_id: int) -> list[types.Content]:
        """Retrieve copy of conversation history for a given user.

        Args:
            user_id: Telegram user identifier.

        Returns:
            List of types.Content representing conversation turns.
        """
        return list(self._storage.get(user_id, []))

    def clear_history(self, user_id: int) -> None:
        """Clear conversation history for a specific user.

        Args:
            user_id: Telegram user identifier.
        """
        if user_id in self._storage:
            del self._storage[user_id]
            logger.info(f"Foydalanuvchi [{user_id}] suhbat tarixi tozalandi")

    def remove_last_turn(self, user_id: int) -> types.Content | None:
        """Remove and return the most recent turn for a user (rollback on API failure).

        Args:
            user_id: Telegram user identifier.

        Returns:
            The removed turn, or None if history was empty.
        """
        history = self._storage.get(user_id)
        if history:
            turn = history.pop()
            if not history:
                del self._storage[user_id]
            logger.debug(f"Foydalanuvchi [{user_id}] ning so'nggi turni bekor qilindi (role={turn.role})")
            return turn
        return None

    def count(self, user_id: int) -> int:
        """Return the current number of turns in history for a user."""
        return len(self._storage.get(user_id, []))


# Global shared instance
memory_service: MemoryService = MemoryService()
